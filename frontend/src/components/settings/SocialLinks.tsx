const SOCIAL_PLATFORMS = [
  { key: "facebookUrl" as const, label: "Facebook", Icon: FacebookIcon },
  { key: "instagramUrl" as const, label: "Instagram", Icon: InstagramIcon },
  { key: "tiktokUrl" as const, label: "TikTok", Icon: TikTokIcon },
  { key: "snapchatUrl" as const, label: "Snapchat", Icon: SnapchatIcon },
  { key: "youtubeUrl" as const, label: "YouTube", Icon: YoutubeIcon },
  { key: "twitterUrl" as const, label: "X (Twitter)", Icon: TwitterIcon },
];

export function SocialLinks({ className, iconClassName = "h-4 w-4" }: SocialLinksProps) {
  const settings = useSiteSettings();

  const links = SOCIAL_PLATFORMS.filter((p) => settings[p.key]);

  if (links.length === 0) return null;

  return (
    <div className={cn("flex gap-3", className)}>
      {links.map(({ key, label, Icon }) => (
        <a
          key={key}
          href={settings[key]!}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label}
          className="rounded-lg bg-slate-800 p-2 transition-colors hover:bg-amber-500 hover:text-slate-900"
        >
          <Icon className={iconClassName} />
        </a>
      ))}
    </div>
  );
}
